#!/usr/bin/env bash
# hooks.hygiene, hooks.installed, ci.pinned:pre-commit, deps.bot (pre-commit ecosystem) and ci.pr-title rows
# of audit.sh in throwaway repos (no remote, no network).
# Usage: test-audit-hooks.sh   (exits 0 when every case passes; VERBOSE=1 prints each row's detail)
set -u
dir=$(cd "$(dirname "$0")/.." && pwd)
audit="$dir/scripts/audit.sh"
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
export HOME="$tmp/home" GIT_CONFIG_GLOBAL="$tmp/home/gitconfig"
mkdir -p "$HOME"; git config --global user.name t; git config --global user.email t@t
fail=0

# case <row-id> <name> <expected-status|none> <setup-commands>
case_() {
  local id=$1 name=$2 want=$3 setup=$4 repo="$tmp/$2" line got
  git init -q -b main "$repo"
  (cd "$repo" && eval "$setup" && git add -A) >/dev/null 2>&1
  line=$(cd "$repo" && "$audit" 2>/dev/null | grep -P "^${id//./\\.}\t")
  got=$(cut -f2 <<<"$line"); got=${got:-none}
  if [ "$got" = "$want" ]; then echo "ok   $id $name${VERBOSE:+  ${line#*$'\t'}}"
  else echo "FAIL $id $name: expected $want, got: ${line:-<no row>}"; fail=1; fi
}
node='echo "{\"name\":\"x\",\"private\":true}" >package.json'
plain="mkdir .githooks && cp '$dir/assets/githooks/pre-commit' '$dir/assets/githooks/pre-push' .githooks/"
fw_stub() { printf 'mkdir -p .git/hooks && for h in %s; do printf "#!/bin/sh\\n# File generated by pre-commit: https://pre-commit.com\\n" >.git/hooks/$h; chmod +x .git/hooks/$h; done' "$1"; }
fw_cfg() { printf "printf '%s' >.pre-commit-config.yaml" "$1"; }
readme='echo "Run pre-commit install after cloning." >README.md'
commits() { printf 'l=%q; IFS=,; for s in $l; do git commit -q --allow-empty -m "$s"; done; unset IFS' "$1"; }
sha=0123456789abcdef0123456789abcdef01234567

# hooks.hygiene
case_ hooks.hygiene  none-at-all      missing "$node"
case_ hooks.hygiene  asset-hook       ok      "$node; $plain; git config core.hooksPath .githooks"
case_ hooks.hygiene  fw-hooks         ok      "$(fw_cfg 'repos:\n- repo: https://github.com/pre-commit/pre-commit-hooks\n  rev: v5.0.0\n  hooks:\n  - id: check-merge-conflict\n  - id: check-added-large-files\n')"
case_ hooks.hygiene  fw-only-conflict drift   "$(fw_cfg 'repos:\n- repo: https://github.com/pre-commit/pre-commit-hooks\n  rev: v5.0.0\n  hooks:\n  - id: check-merge-conflict\n')"
case_ hooks.hygiene  push-stage-only  missing "$(fw_cfg 'repos:\n- repo: https://github.com/pre-commit/pre-commit-hooks\n  rev: v5.0.0\n  hooks:\n  - id: check-merge-conflict\n    stages: [pre-push]\n  - id: check-added-large-files\n    stages: [pre-push]\n')"

# hooks.installed
case_ hooks.installed nothing          n/a     "$node"
case_ hooks.installed local-only       ok      "mkdir -p .git/hooks && cp '$dir/assets/githooks/pre-commit' .git/hooks/ && chmod +x .git/hooks/pre-commit"
case_ hooks.installed plain-active     ok      "$node; $plain; git config core.hooksPath .githooks; echo 'git config core.hooksPath .githooks' >README.md"
case_ hooks.installed plain-inactive   drift   "$node; $plain; echo 'git config core.hooksPath .githooks' >README.md"
case_ hooks.installed plain-undocumented drift "$node; $plain; git config core.hooksPath .githooks"
case_ hooks.installed fw-installed     ok      "$(fw_cfg 'default_install_hook_types: [pre-commit, pre-push]\nrepos:\n- repo: local\n  hooks:\n  - id: t\n    entry: pytest\n    stages: [pre-push]\n'); $(fw_stub 'pre-commit pre-push'); $readme"
case_ hooks.installed fw-not-installed drift   "$(fw_cfg 'repos:\n- repo: local\n  hooks:\n  - id: r\n    entry: ruff check\n'); $readme"
case_ hooks.installed fw-push-not-default drift "$(fw_cfg 'repos:\n- repo: local\n  hooks:\n  - id: t\n    entry: pytest\n    stages: [pre-push]\n'); $(fw_stub 'pre-commit pre-push'); $readme"
case_ hooks.installed fw-push-missing  drift   "$(fw_cfg 'default_install_hook_types: [pre-commit, pre-push]\nrepos:\n- repo: local\n  hooks:\n  - id: t\n    entry: pytest\n    stages: [pre-push]\n'); $(fw_stub pre-commit); $readme"
case_ hooks.installed fw-foreign-hook  drift   "$(fw_cfg 'repos:\n- repo: local\n  hooks:\n  - id: r\n    entry: ruff check\n'); mkdir -p .git/hooks && printf '#!/bin/sh\\nexit 0\\n' >.git/hooks/pre-commit && chmod +x .git/hooks/pre-commit; $readme"
case_ hooks.installed fw-hookspath     drift   "$(fw_cfg 'repos:\n- repo: local\n  hooks:\n  - id: r\n    entry: ruff check\n'); git config core.hooksPath .hk; $readme"
case_ hooks.installed husky-ok         ok      "echo '{\"name\":\"x\",\"private\":true,\"scripts\":{\"prepare\":\"husky\"}}' >package.json; mkdir -p .husky/_ && printf 'npx lint-staged\\n' >.husky/pre-commit && printf '#!/bin/sh\\n' >.husky/_/pre-commit && chmod +x .husky/_/pre-commit && git config core.hooksPath .husky/_"
case_ hooks.installed husky-no-prepare drift   "$node; mkdir -p .husky/_ && printf 'npx lint-staged\\n' >.husky/pre-commit && printf '#!/bin/sh\\n' >.husky/_/pre-commit && chmod +x .husky/_/pre-commit && git config core.hooksPath .husky/_"

# ci.pinned:pre-commit and deps.bot covering the pre-commit ecosystem
case_ ci.pinned:pre-commit tag      drift "$(fw_cfg 'repos:\n- repo: https://github.com/gitleaks/gitleaks\n  rev: v8.30.1\n  hooks:\n  - id: gitleaks\n')"
case_ ci.pinned:pre-commit frozen   ok    "$(fw_cfg "repos:\n- repo: https://github.com/gitleaks/gitleaks\n  rev: $sha  # frozen: v8.30.1\n  hooks:\n  - id: gitleaks\n- repo: local\n  hooks:\n  - id: x\n    entry: x\n")"
case_ ci.pinned:pre-commit fw-local-repo none "$(fw_cfg 'repos:\n- repo: local\n  hooks:\n  - id: x\n    entry: x\n')"
dep() { printf "mkdir -p .github && printf 'version: 2\\nupdates:\\n  - package-ecosystem: %s\\n' >.github/dependabot.yml" "$1"; }
case_ deps.bot no-pre-commit-eco    drift "$(fw_cfg "repos:\n- repo: https://github.com/gitleaks/gitleaks\n  rev: $sha  # frozen: v8.30.1\n  hooks:\n  - id: gitleaks\n"); $(dep npm)"
case_ deps.bot pre-commit-eco       ok    "$(fw_cfg "repos:\n- repo: https://github.com/gitleaks/gitleaks\n  rev: $sha  # frozen: v8.30.1\n  hooks:\n  - id: gitleaks\n"); $(dep pre-commit)"

# ci.pr-title
wf() { printf "mkdir -p .github/workflows && cp '%s' .github/workflows/pr-title.yml" "$1"; }
case_ ci.pr-title no-convention     n/a     "$(commits 'init,wip,more,stuff,fix')"
case_ ci.pr-title history           missing "$(commits 'feat: a,fix: b,chore: c,docs: d,feat(x)!: e')"
case_ ci.pr-title commitlint-file   missing "echo 'module.exports={}' >commitlint.config.js"
case_ ci.pr-title template          ok      "echo 'module.exports={}' >commitlint.config.js; $(wf "$dir/assets/workflows/pr-title.yml")"
# title interpolated straight into run: (brackets become braces, so this file holds no template placeholder)
tr '[]' '{}' >"$tmp/bad.yml" <<'EOF'
on:
  pull_request:
jobs:
  t:
    runs-on: ubuntu-latest
    steps:
      - run: echo "$[[ github.event.pull_request.title ]]" | grep -qE '^feat'
EOF
case_ ci.pr-title injectable        drift   "echo 'module.exports={}' >commitlint.config.js; $(wf "$tmp/bad.yml")"

exit $fail
